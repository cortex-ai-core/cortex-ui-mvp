import { mkdir, writeFile, appendFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { devRun, github, imageTag, validateWebArtifact } from './dev-release.mjs';
const source = await devRun('cortex-ai-core/cortex-ui-mvp', process.argv[2]);
const backend = await devRun('cortex-ai-core/cortex-mvp', process.argv[3]);
source.backend = { ...backend, apiTag: imageTag(`git-${backend.commit}-${backend.runId}-${backend.runAttempt}`) };
const artifacts = await (await github(`${source.repository}/actions/runs/${source.runId}/artifacts?per_page=100`)).json();
const artifact = validateWebArtifact(artifacts.artifacts.find(a => a.name === 'static-web'));
source.artifact = { id: artifact.id, digest: artifact.digest };
const response = await github(`${source.repository}/actions/artifacts/${artifact.id}/zip`);
const archive = Buffer.from(await response.arrayBuffer());
if (`sha256:${createHash('sha256').update(archive).digest('hex')}` !== artifact.digest) throw new Error('Frontend artifact checksum mismatch.');
await mkdir('.local/promotion', { recursive: true });
await writeFile('.local/promotion/static-web.zip', archive);
const paths = execFileSync('unzip', ['-Z1', '.local/promotion/static-web.zip'], { encoding: 'utf8' }).trim().split('\n');
if (paths.some(path => path.startsWith('/') || path.split('/').includes('..'))) throw new Error('Unsafe artifact entry.');
await mkdir('out', { recursive: true });
execFileSync('unzip', ['-q', '.local/promotion/static-web.zip', '-d', 'out']);
await writeFile('.local/promotion/source.json', JSON.stringify(source, null, 2));
if (process.env.GITHUB_OUTPUT) await appendFile(process.env.GITHUB_OUTPUT, `backend_api_tag=${source.backend.apiTag}\n`);
console.log(JSON.stringify(source));
